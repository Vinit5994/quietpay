/**
 * Regenerates packages/shared/src/abi/QuietPay.ts (ABI, `as const`) and packages/shared/src/deployments.ts
 * from the Foundry build output and contracts/deployments/whitechain-sepolia.json.
 *
 *   pnpm abi:export        (runs `forge build` first)
 */
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const artifact = resolve(root, "contracts/out/QuietPay.sol/QuietPay.json");
const deployment = resolve(root, "contracts/deployments/whitechain-sepolia.json");
const abiOut = resolve(root, "packages/shared/src/abi/QuietPay.ts");
const deploymentsOut = resolve(root, "packages/shared/src/deployments.ts");

execSync("forge build", { cwd: resolve(root, "contracts"), stdio: "inherit" });

const { abi } = JSON.parse(readFileSync(artifact, "utf8")) as { abi: unknown[] };
writeFileSync(
  abiOut,
  `// Generated by scripts/export-abi.ts from contracts/out/QuietPay.sol/QuietPay.json. Do not edit.\n` +
    `export const quietPayAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`wrote ${abiOut} (${abi.length} entries)`);

let address = "null";
let deployBlock = "null";
if (existsSync(deployment)) {
  const d = JSON.parse(readFileSync(deployment, "utf8")) as { QuietPay: string; deployBlock: number };
  address = JSON.stringify(d.QuietPay);
  deployBlock = `${d.deployBlock}n`;
  console.log(`QuietPay ${d.QuietPay} from block ${d.deployBlock}`);
} else {
  console.log("no deployments/whitechain-sepolia.json yet; QUIETPAY_ADDRESS stays null");
}
writeFileSync(
  deploymentsOut,
  `// Generated by scripts/export-abi.ts from contracts/deployments/whitechain-sepolia.json. Do not edit.\n` +
    `import type { Address } from "viem";\n\n` +
    `/** QuietPay on Whitechain Sepolia (null until A5 deploys it). */\n` +
    `export const QUIETPAY_ADDRESS: Address | null = ${address};\n` +
    `/** Indexer start block. */\n` +
    `export const QUIETPAY_DEPLOY_BLOCK: bigint | null = ${deployBlock};\n`,
);
console.log(`wrote ${deploymentsOut}`);
